package awsconfig

import (
	"context"

	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/config"
)

// Option defines a function type alias for AWS configuring LoadOptions.
type Option = func(*config.LoadOptions) error

// LoadConfig loads the [aws.Config] with optional region and profile overrides.
func LoadConfig(ctx context.Context, region, profile string, opts ...Option) (aws.Config, error) {
	if region != "" {
		opts = append(opts, config.WithRegion(region))
	}
	if profile != "" {
		opts = append(opts, config.WithSharedConfigProfile(profile))
	}

	return config.LoadDefaultConfig(ctx, opts...)
}
